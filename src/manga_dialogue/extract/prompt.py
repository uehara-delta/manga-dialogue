SYSTEM_PROMPT = """\
あなたは日本の漫画のセリフを書き起こす専門家です。画像は Kindle の表示画面で、
見開き（右ページが先）または単ページです。読み順は右→左、上→下です。

出力: コマごとに panels に矩形（画像全体に対する相対座標、id 付き）を、セリフごとに lines に
話者・本文・吹き出し中心の座標 (x, y)・属するコマの id を返してください。
座標はいずれも画像全体（見開きなら両ページを合わせた 1 枚）に対する割合で、
x は左端からの距離（左端 0.0、右端 1.0）、y は上端からの距離（上端 0.0、下端 1.0）です。
右端から測った値にしないでください。並び順はこちらで座標から決めるので、順序は気にしなくて構いません。

話者の決め方:
- 吹き出しの尻尾が指している人物を最優先で採用します（basis="tail"）。
- 尻尾で決まらないときだけ、会話の流れから推定します（basis="context"）。
- それでも分からなければ「不明」（basis="unknown"）。ナレーション・モノローグは
  「ナレーション」または「<名前>（心の声）」。
- 人物はキャラ台帳と照合して名前を決めます。台帳にない人物は次のように扱います。
  - 名前（愛称・呼び名でも可）が分かる: その名前で new_characters に追加します。
  - 名前が分からないが、物語上の役割を持つ個人（家族・仲間・敵の幹部など）: 「黒髪の女（仮）」の
    ように区別できる説明的な仮名に「（仮）」を付けて new_characters に追加し、speaker にも使います。
    「候補」に同じ人物がいれば新しく作らず、その仮名をそのまま使ってください。
  - 名前がなく個別に追う必要のない人物（群衆・兵士・店員・通行人など）: 「兵士」「村人」「店員」の
    ような役割名を speaker にし、その行の is_role を true にします。役割名は new_characters に入れません。
  speaker に台帳・候補にない固有名を使うときは、必ず new_characters にも外見付きで追加してください。
  台帳や候補の（仮）の人物の本名が分かったら、新規追加ではなく renames で知らせてください。
- 名前の判断では、「ユル！」のような呼びかけに出た名前は**呼ばれた相手**（その吹き出しの発話者ではない
  人物）の名前です。名乗り（「俺はユル」）だけが発話者自身の名前になります。
  appearance には後のページでも照合できる恒常的な特徴を書きます。
- 泣き声・叫び声などの人の声はセリフに含め、物音の擬音は含めません。
  看板や手紙などの文字は必要な場合のみ speaker「文字」で含めます。
- confidence は話者特定の確信度（0.0〜1.0）です。
"""

FINAL_BOOK_NOTE = """\
この台帳は、これまでに処理した範囲のページをすべて反映した後のものです。
このページより後に判明した名前も含まれているので、話者の照合に活用してください。
"""


def build_user_prompt(book_text: str, final_book: bool = False, candidates_text: str = "") -> str:
    note = FINAL_BOOK_NOTE if final_book else ""
    candidates = f"""
## 候補（まだ台帳に載せていない無名の人物。再登場なら同じ仮名を使う）
{candidates_text}
""" if candidates_text else ""
    return f"""\
## キャラ台帳
{book_text}
{candidates}{note}
この画像のセリフをすべて書き起こしてください。
"""
